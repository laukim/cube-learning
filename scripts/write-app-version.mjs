import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  DEV_VERSION,
  formatReleaseVersion,
  releaseBuildNumber,
  releaseMajor,
} from "../worker/release-version.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
let commitCount = 0;
try {
  commitCount = Number(
    execFileSync("git", ["rev-list", "--count", "HEAD"], { cwd: root, encoding: "utf8" }).trim()
  );
} catch {
  commitCount = 0;
}

const build = releaseBuildNumber({
  command: process.env.WRANGLER_COMMAND || "",
  workersCi: process.env.WORKERS_CI || "",
  commitCount,
});
const major = releaseMajor(pkg.version);
const version = build > 0 ? formatReleaseVersion(major, build) : DEV_VERSION;
const source = `// Generated by scripts/write-app-version.mjs. Local static serves keep v0.0.0-dev until a production deploy.\nexport const APP_VERSION = ${JSON.stringify(version)};\nexport const APP_BUILD = ${build};\nexport const APP_MAJOR = ${JSON.stringify(major)};\n`;
const dest = join(root, "worker", "app-version.js");
let current = "";
try {
  current = readFileSync(dest, "utf8");
} catch {
  current = "";
}
if (current !== source) writeFileSync(dest, source);
console.log(version);
